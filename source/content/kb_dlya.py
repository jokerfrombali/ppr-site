def register(reg, G):
    render_category, render_sub = G['render_category'], G['render_sub']
    reg('/ppr-dlya/', HUB['title'], HUB['desc'], HUB['h1'],
        lambda: render_category(HUB, SUBS, '/ppr-dlya/'), crumb='ППР под требования заказчика',
        faq_items=HUB['d']['faq'], prio='0.6')
    for s in SUBS:
        u = '/ppr-dlya/' + s['slug'] + '/'
        reg(u, s['title'], s['desc'], s['h1'],
            (lambda ss, uu: (lambda: render_sub(ss, HUB, uu, '/ppr-dlya/')))(s, u),
            faq_items=s['d']['faq'], prio='0.5')
